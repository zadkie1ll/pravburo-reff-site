"""Этапы процедуры, которые видит партнёр (ТЗ, "Статусы приглашённых клиентов"),
привязанные к стадиям воронки Bitrix "Сопровождение" (category_id=2).

Показываются только стадии из этого словаря. Остальные стадии воронки живут в Bitrix
как обычно, но на сайте ничего не меняют: этап у партнёра остаётся прежним, push не
отправляется.

Этапы 1 ("Заявка получена") и 2 ("Консультация проведена") происходят до воронки
"Сопровождение" и стадии в ней не имеют: этап 1 - это заявка без стадии сделки
(DEFAULT_STAGE_LABEL), этап 2 пока нигде не отслеживается.
"""

DEFAULT_STAGE_LABEL = "Заявка получена"

STAGE_LABELS: dict[str, str] = {
    "C2:NEW": "Договор подписан",  # "Новый договор"; партнёр получает аванс
    "C2:PREPARATION": "Документы собраны",  # "Анализ ситуации"
    "C2:UC_0Y0VBU": "Заявление подано в суд",
    "C2:UC_MYA2I0": "Депозит оплачен",  # "ОБСУЖДЕНИЕ депозита"; партнёр получает основную выплату
    "C2:UC_7TR7XT": "Процедура завершена",  # "Завершен"
}


# Стадии воронки "Основная" (category_id=0, продажи), которые партнёр видит в "Выплатах",
# пока договора нет и выплаты ещё нет. Всё остальное в этой воронке = "Анализ ситуации".
# Push по этим стадиям не отправляется.
PAYOUT_STAGE_LABELS: dict[str, str] = {
    "UC_4FX5NE": "Оплата депозита",  # "Договор составлен, ждём оплату"
    "UC_1BEALQ": "Ушел в игнор",  # "Ушли в игнор"
}
DEFAULT_PAYOUT_STAGE_LABEL = "Анализ ситуации"


def is_funnel_2_stage(stage_code: str) -> bool:
    return stage_code.startswith("C2:")


def stage_label(stage_code: str | None) -> str | None:
    """Название этапа для партнёра или None, если стадия не отслеживается."""
    if not stage_code:
        return None
    return STAGE_LABELS.get(stage_code)
