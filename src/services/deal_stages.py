UNKNOWN_SALES_STAGE_LABEL = "В обработке"


def application_status_label(stage_code: str | None) -> str:
    """Статус заявки для партнёра: этап процедуры (воронка "Сопровождение") либо
    состояние продажи (воронка "Основная"). Без сделки - "Заявка получена"."""
    if not stage_code:
        return DEFAULT_STAGE_LABEL
    return (
        STAGE_LABELS.get(stage_code)
        or SALES_STAGE_LABELS.get(stage_code)
        or UNKNOWN_SALES_STAGE_LABEL
    )


def is_funnel_2_stage(stage_code: str) -> bool:
    return stage_code.startswith("C2:")


def stage_label(stage_code: str | None) -> str | None:
    """Название этапа для партнёра или None, если стадия не отслеживается."""
    if not stage_code:
        return None
    return STAGE_LABELS.get(stage_code)
